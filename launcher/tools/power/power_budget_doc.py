#!/usr/bin/env python3
"""Generate the tables and figure of docs/power/Power-Budget.md from the datasheet figures in
docs/power/data/datasheet_currents.json. Nothing here is measured: every row names its datasheet and page.

    python launcher/tools/power/power_budget_doc.py --write
    python launcher/tools/power/power_budget_doc.py --check
    python launcher/tools/power/power_budget_doc.py --figures DIR   # the doc-image runner: only the figure, into DIR
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "launcher/tools"))
sys.path.insert(0, str(ROOT / "launcher/tools/render"))
from doc_tables import markdown
from generated_blocks import replace_block

from docs.plot_style import FIGURE_SIZE, LABEL_SIZE, SLOTS, TITLE_SIZE, picture, save_themes, stacked_barh, style_axes, subplots

DATA = ROOT / "docs/power/data/datasheet_currents.json"
DOCUMENT = ROOT / "docs/power/Power-Budget.md"
CITATIONS = ROOT / "docs/Citations.md"
IMAGES = ROOT / "docs/images/power"
FIGURE_STEM = "power_budget_states"
REGENERATE = "python launcher/tools/power/power_budget_doc.py --write"
MICRO_PER_MILLI = 1000
AWAKE, SLEEP = "awake", "sleep"
FIGURE_COLUMNS = (3, 2)  # width ratios of the milliamp and microamp panels
FIGURE_HEIGHT = 3.8
AMP_BLOCK = "NS4150B amp"
DISPLAY_ON, PLAYING = "display-on", "playing"


def load():
    return json.loads(DATA.read_text(encoding="utf-8"))


def citation_numbers():
    """Citations.md's `[n]` of each anchor key."""
    return {key: int(number) for key, number in re.findall(r'<a id="([^"]+)"></a>\[(\d+)\]', CITATIONS.read_text(encoding="utf-8"))}


def amount(value, decimals=None):
    """A current in mA with its own precision, '-' when the datasheet gives none."""
    if value is None:
        return "-"
    text = f"{value:.4f}".rstrip("0").rstrip(".") if decimals is None else f"{value:.{decimals}f}"
    return text or "0"


def source_cell(figure, numbers):
    key = figure["source"]
    return f"<sup>[[{numbers[key]}]](../Citations.md#{key})</sup> p. {figure['page']}, {figure['table']}"


def basis(figure):
    """The figure a bar and the 'best figure' sum use: typ, else max."""
    return figure["typ"] if figure["typ"] is not None else figure["max"]


def totals(data, state):
    """typ sum over rows with a typ, max sum (max, else typ), rows with no typ, and the best-figure sum."""
    figures = [data["figures"][name] for name in state["figures"]]
    typ = sum(f["typ"] for f in figures if f["typ"] is not None)
    high = sum(f["max"] if f["max"] is not None else f["typ"] for f in figures)
    return {"typ": typ, "max": high, "no_typ": sum(f["typ"] is None for f in figures),
            "best": sum(basis(f) for f in figures)}


def state_table(data, state, numbers):
    rows = []
    for name in state["figures"]:
        figure = data["figures"][name]
        label = figure["label"] + (" (derived)" if figure.get("derived") else "")
        rows.append((figure["block"], label, amount(figure["typ"]), amount(figure["max"]), source_cell(figure, numbers), figure["note"]))
    total = totals(data, state)
    missing = f" ({total['no_typ']} row without a typ)" if total["no_typ"] == 1 else f" ({total['no_typ']} rows without a typ)" if total["no_typ"] else ""
    rows.append(("**Sum**", f"rows listed above{missing}", f"**{amount(total['typ'], 3)}**", f"**{amount(total['max'], 3)}**", "", "max sum uses typ where a row has no max"))
    return f"### {state['title']}\n\n{state['text']}\n\n" + markdown(("Block", "Figure", "Typ mA", "Max mA", "Source", "Condition"), rows)


def states_block(data, numbers):
    return "> Generated by: `" + REGENERATE + "`\n\n" + "\n".join(state_table(data, state, numbers) for state in data["states"])


def summary_table(data):
    rows = []
    for state in data["states"]:
        total = totals(data, state)
        rows.append((state["title"], amount(total["typ"], 3), amount(total["max"], 3),
                     data["figures"][next(n for n in state["figures"] if data["figures"][n]["block"] == AMP_BLOCK)]["label"]))
    return markdown(("State", "Typ mA", "Max mA", "Amplifier in this state"), rows)


def bars(data, state):
    """One state's stacked segments: each block's best datasheet figure, in the block order."""
    values = {block: 0.0 for block in data["blocks"]}
    for name in state["figures"]:
        figure = data["figures"][name]
        values[figure["block"]] += basis(figure)
    return values


def render_figure(data, directory=IMAGES):
    colours = dict(zip(data["blocks"], SLOTS))
    fig, axes = subplots(1, 2, (FIGURE_SIZE[0], FIGURE_HEIGHT), gridspec_kw={"width_ratios": FIGURE_COLUMNS})
    for axis, kind, scale, unit in ((axes[0], AWAKE, 1, "mA"), (axes[1], SLEEP, MICRO_PER_MILLI, "uA")):
        rows, ends = [], []
        for state in (s for s in data["states"] if s["kind"] == kind):
            values = bars(data, state)
            rows.append((state["title"], [(block, values[block] * scale) for block in data["blocks"] if values[block]]))
            ends.append(f"{sum(values.values()) * scale:,.0f} {unit}")
        stacked_barh(axis, rows, colours, ends)
        style_axes(axis, f"{'Awake' if kind == AWAKE else 'Asleep'} states ({unit})")
    handles = {}
    for axis in axes:
        handles.update(zip(*reversed(axis.get_legend_handles_labels())))
    fig.legend(handles.values(), handles.keys(), loc="outside lower center", ncol=4, fontsize=LABEL_SIZE, frameon=False)
    save_themes(fig, Path(directory) / f"{FIGURE_STEM}.png")


def summary_block(data):
    return ("> Generated by: `" + REGENERATE + "`\n\n" + picture(FIGURE_STEM, "Datasheet current of each block in each power state", "../images/power")
            + summary_table(data))


def unknown_block(data):
    return "> Generated by: `" + REGENERATE + "`\n\n" + markdown(("Not budgeted", "Why"), data["unknown"])


def v2_table(data, numbers):
    rows = [(data["figures"][name]["label"], amount(data["figures"][name]["typ"]), source_cell(data["figures"][name], numbers))
            for name in ("co5300_sleep", "co5300_ultra_low")]
    return "> Generated by: `" + REGENERATE + "`\n\n" + markdown(("V2 driver figure", "Typ mA", "Source"), rows)


def generate(check):
    data, numbers = load(), citation_numbers()
    if not check:
        render_figure(data)
    changed = False
    for name, body in (("power-summary", summary_block(data)), ("power-states", states_block(data, numbers)),
                       ("power-v2-driver", v2_table(data, numbers)), ("power-unknown", unknown_block(data))):
        changed |= replace_block(DOCUMENT, name, body, check=check)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--figures", type=Path, metavar="DIR")
    args = parser.parse_args()
    if args.figures:
        render_figure(load(), args.figures)
        return
    changed = generate(args.check)
    if args.check and changed:
        sys.exit("docs/power/Power-Budget.md is out of date: run " + REGENERATE)


if __name__ == "__main__":
    main()
