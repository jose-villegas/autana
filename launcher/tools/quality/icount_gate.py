#!/usr/bin/env python3
"""Ratchet only named one-core kernels from an --icount serial capture."""
import argparse
import ast
import math
from pathlib import Path
import re
import sys

from complexity_gate import report
from py_constant import module_constant

ROOT = Path(__file__).resolve().parents[3]
BASELINE_PATH = Path(__file__).with_name("icount_baseline.txt")
SUPPORT_PATH = ROOT / "launcher/packages/testkit/include/testkit/bench.h"
QEMU_PATH = ROOT / "launcher/test/qemu_run.py"


def support_define(name):
    match = re.search(rf"^#define {name}\s+(.+)$", SUPPORT_PATH.read_text(encoding="utf-8"), re.M)
    if match is None:
        raise ValueError(f"{SUPPORT_PATH}: missing {name}")
    return ast.literal_eval(match[1])


LINE_PREFIX = support_define("BENCH_ICOUNT_PREFIX")
INFO_PREFIX = support_define("BENCH_ICOUNT_INFO_PREFIX")
INFO_MARKER = "info"
TOLERANCE = 1 / support_define("BENCH_ICOUNT_TOLERANCE_DENOMINATOR")
NS_PER_US = 1000
ICOUNT_SHIFT = module_constant(QEMU_PATH, "ICOUNT_SHIFT")
ROW = re.compile(rf"({LINE_PREFIX}|{INFO_PREFIX}) (\S+) us=(\d+) reps=(\d+)")


class InstructionRows(dict):
    def __init__(self):
        super().__init__()
        self.info = set()


def parse_log(text):
    rows = InstructionRows()
    for line in text.splitlines():
        if not line.startswith((LINE_PREFIX, INFO_PREFIX)):
            continue
        match = ROW.fullmatch(line)
        if match is None:
            raise ValueError(f"malformed {LINE_PREFIX} row: {line}")
        prefix, name, us, reps = match.groups()
        if prefix == INFO_PREFIX:
            rows.info.add(name)
        us, reps = int(us), int(reps)
        if name in rows or reps <= 0:
            raise ValueError(f"{name}: duplicate row or invalid reps")
        rows[name] = us * NS_PER_US / (1 << ICOUNT_SHIFT) / reps
    if not rows:
        raise ValueError(f"no {LINE_PREFIX} lines: no instruction measurements")
    return rows


def load_baseline(path):
    rows = InstructionRows()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        value, name, *marker = line.split("\t")
        if marker:
            if marker != [INFO_MARKER]:
                raise ValueError(f"invalid baseline marker: {line}")
            rows.info.add(name)
        if name in rows or not math.isfinite(float(value)) or float(value) <= 0:
            raise ValueError(f"invalid baseline entry: {line}")
        rows[name] = float(value)
    return rows


def compare(measured, baseline):
    errors = []
    info = getattr(measured, "info", set()) | getattr(baseline, "info", set())
    for name in sorted((measured.keys() | baseline.keys()) - info):
        if name not in baseline:
            errors.append(f"{name}: no baseline entry; --update-baseline in the same PR")
        elif name not in measured:
            errors.append(f"{name}: no measurement")
        elif measured[name] > baseline[name] * (1 + TOLERANCE):
            errors.append(f"{name}: {measured[name]:g} > {baseline[name]:g}; "
                          "raise only with a stated reason: --update-baseline in the same PR")
        elif measured[name] < baseline[name] * (1 - TOLERANCE):
            errors.append(f"{name}: {measured[name]:g} < {baseline[name]:g}; "
                          "lower the baseline in the same PR: --update-baseline")
        else:
            print(f"PASS {name}: {measured[name]:g} instructions/rep (baseline {baseline[name]:g})")
    return errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("log", type=Path)
    parser.add_argument("--update-baseline", action="store_true")
    parser.add_argument("--baseline", type=Path, default=BASELINE_PATH)
    args = parser.parse_args(argv)
    try:
        measured = parse_log(args.log.read_text(encoding="utf-8", errors="replace"))
        if args.update_baseline:
            lines = ["# generated by launcher/tools/quality/icount_gate.py --update-baseline",
                     "# instructions\tname[\t" + INFO_MARKER + "]"]
            lines.extend(f"{round(measured[name])}\t{name}" +
                         (f"\t{INFO_MARKER}" if name in measured.info else "") for name in sorted(measured))
            args.baseline.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
            print(f"Updated {args.baseline}")
            return 0
        errors = compare(measured, load_baseline(args.baseline))
    except (OSError, ValueError) as error:
        errors = [str(error)]
    report([(str(args.log), 1, f"FAIL {error}") for error in errors], "error")
    return int(bool(errors))


if __name__ == "__main__":
    sys.exit(main())
