#!/bin/sh
#
# Every face example in tools/render/ui_examples/ drawn on a host, the images
# docs/ui/ shows, see ui_examples_render_host.c and docs/tools/Render-Harness.md.
#
# The folder is the list: <name>.c is a control, rendered at rest in both
# orientations and in each state of the scene's STATES; screens/<name>.c is a
# whole screen, rendered at rest in both. Each file defines <name>_example_t
# and bool <name>_example(<name>_example_t*), and gets a generated wrapper
# that holds its state, so a file missing either name fails the build.
set -eu
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
LAUNCHER=$(CDPATH= cd -- "$SCRIPT_DIR/../../.." && pwd)
EXAMPLES=$SCRIPT_DIR/../ui_examples
WRAPPERS=tools/results/render/ui_examples_wrappers

scene_name=ui_examples
scene_ui=1
scene_assets="main/engine"
scene_includes="tools/render/ui_examples"
scene_sources="
main/services/tune.c
tools/render/scenes/ui_examples_render_host.c
"
scene_renders=
list=

# The states a control is rendered in besides rest; the C side's STATES
# says what each does. no-pack is rest with no asset pack.
STATES="pressed tapped disabled"

mkdir -p "$LAUNCHER/$WRAPPERS"
for file in "$EXAMPLES"/*.c "$EXAMPLES"/screens/*.c; do
    [ -f "$file" ] || continue
    name=$(basename "$file" .c)
    relative=${file#"$EXAMPLES"/}
    wrapper=$LAUNCHER/$WRAPPERS/${name}_wrapper.c
    printf '%s\n' \
        "/* Generated by ui_examples_render_host.sh: holds $relative's state. */" \
        "#include \"$relative\"" \
        "static ${name}_example_t state;" \
        "bool ui_example_${name}(void) { return ${name}_example(&state); }" > "$wrapper"
    scene_sources="$scene_sources $WRAPPERS/${name}_wrapper.c"
    list="${list}X($name)"
    scene_renders="$scene_renders
$name|--example $name --state rest --quarter 0|368x448|crop
$name-landscape|--example $name --state rest --quarter 1|448x368|crop"
    case "$relative" in screens/*) continue ;; esac
    for state in $STATES; do
        scene_renders="$scene_renders
$name-$state|--example $name --state $state --quarter 0|368x448|crop"
    done
    scene_renders="$scene_renders
$name-no-pack|--example $name --state rest --quarter 0|368x448|crop|nopacks"
done
if [ -z "$list" ]; then
    echo "ERROR: no examples in $EXAMPLES" >&2
    exit 1
fi
scene_defines="-DUI_EXAMPLES=$list"

. "$SCRIPT_DIR/../render_scene.sh"
render_scene_run "$@"
