"""Analyze playback WAV takes and render per-arm DSP tables."""
import math
from statistics import median
from pathlib import Path

from audio.mic import mic_metrics as metrics
from audio.mic.playback_dsp_capture import arms, TONE_HZ, LOW_TONE_HZ, GAIN
from audio_doc_blocks import number
from autana_runner import recorded_take
from build.c_header import read_define

BLOCK_SAMPLES = read_define(Path(__file__).resolve().parents[3] / 'main/audio/audio_codec.h',
                            'AUDIO_CODEC_BLOCK_SAMPLES')
ACTIVE_BAND = (metrics.SPEECH_LOW_HZ, metrics.SPEECH_HIGH_HZ)
LOW_BAND_HZ = 200
CLICK_WINDOW_MS = 20
BLOCKS = ('drc', 'eq', 'dac-ramp', 'adc-ramp')


def take_metrics(path, state, ramp, check=None):
    return metrics.read_take_metrics(path, lambda samples, rate: analyze_take(samples, rate, state, ramp), check)


def analyze_take(samples, rate, state, ramp):
    if state['rate'] != rate or state['samples'] != len(samples):
        raise ValueError('take and MIC_STATE differ')
    if not ramp:
        return dict(active=metrics.active_level_db(samples, rate, ACTIVE_BAND),
                    clips=metrics.clip_count(samples), low=metrics.low_band_db(samples, LOW_BAND_HZ, rate))
    writes = state.get('writes', [])
    if len(writes) != 2:
        raise ValueError('ramp take needs both applied writes')
    positions = [write[0] * BLOCK_SAMPLES for write in writes]
    if not 0 < positions[0] < positions[1] < len(samples):
        raise ValueError('invalid ramp write blocks')
    excess = metrics.click_excess_db(samples, rate, positions, CLICK_WINDOW_MS)
    result = {}
    for index, (at, click) in enumerate(zip(positions, excess)):
        end = positions[index + 1] if index + 1 < len(positions) else len(samples)
        result['click' + str(index)] = click
        result['settle' + str(index)] = metrics.settle_ms(samples, rate, at, end)
    return result


def playback_data(path, records, check=None):
    expected = list(arms())
    groups = {}
    current = None
    runs = None
    for command, reply in records:
        if command == ['runs']:
            if runs is not None or not isinstance(reply, int) or reply <= 0:
                raise ValueError('invalid playback run count')
            runs = reply
        elif command == ['arm']:
            index = reply['index']
            setting = {key: value for key, value in reply.items() if key != 'index'}
            if not isinstance(index, int) or not 0 <= index < len(expected) or setting != expected[index] or index in groups:
                raise ValueError('unknown or duplicate playback arm')
            current = groups[index] = dict(setting=setting, takes=[], tones={})
        elif command[:2] == ['mic', 'record']:
            if current is None:
                raise ValueError('take without arm')
            current['takes'].append(take_metrics(*recorded_take(path, command, reply),
                                                 current['setting']['block'].endswith('-ramp'), check))
        elif command[:1] == ['tone']:
            if current is None or reply['hz'] != int(command[1]):
                raise ValueError('invalid playback tone')
            current['tones'].setdefault(reply['hz'], []).append(reply)
    if runs is None or set(groups) != set(range(len(expected))):
        raise ValueError('missing playback arms')
    for group in groups.values():
        setting = group['setting']
        frequencies = ((TONE_HZ, LOW_TONE_HZ) if setting['block'] == 'eq' else
                       (TONE_HZ,) if setting['block'] == 'drc' and setting['volume'] == GAIN else ())
        if (len(group['takes']) != runs or set(group['tones']) != set(frequencies)
                or any(len(values) != runs for values in group['tones'].values())):
            raise ValueError('missing playback runs or tones')
        for tone in (tone for values in group['tones'].values() for tone in values):
            if any((tone[key] is None and key != 'thd_db')
                   or (tone[key] is not None and (not isinstance(tone[key], (int, float)) or not math.isfinite(tone[key])))
                   for key in ('thd_db', 'peak_dbfs')):
                raise ValueError('invalid tone metric')
    return groups


def render(path, records, markdown, check=None):
    groups = playback_data(path, records, check)
    body = '> Generated by: `python launcher/tools/audio/audio_doc_tables.py --write`\n\n'
    body += 'Music levels use active frames in 300–3400 Hz. Cells are medians across takes; unsettled steps are n/a.\n\n'
    for block in BLOCKS:
        rows = []
        for group in groups.values():
            setting = group['setting']
            if setting['block'] != block:
                continue
            def value(key):
                values = [take[key] for take in group['takes']]
                return number(median(values)) if all(v is not None for v in values) else 'n/a'
            if block.endswith('-ramp'):
                rows.append((setting['ramp'], value('click0'), value('settle0'), value('click1'), value('settle1')))
            else:
                label = ('default' if setting['drc'] else 'off') if block == 'drc' else setting['cutoff'] or 'bypass'
                row = [setting['volume'], label, value('active'), value('clips')]
                if block == 'eq':
                    row.append(value('low'))
                for hz in ((TONE_HZ, LOW_TONE_HZ) if block == 'eq' else (TONE_HZ,)):
                    tones = group['tones'].get(hz, [])
                    for key in ('thd_db', 'peak_dbfs'):
                        values = [tone[key] for tone in tones if tone[key] is not None]
                        row.append(number(median(values)) if values else 'n/a')
                rows.append(row)
        columns = (['Ramp', 'Down click excess (dB)', 'Down settle (ms)', 'Up click excess (dB)', 'Up settle (ms)']
                   if block.endswith('-ramp') else
                   ['Codec (%)', 'DRC' if block == 'drc' else 'HPF (Hz)', 'Active level (dBFS)', 'Mic clips']
                   + (['Below 200 Hz (dBFS)'] if block == 'eq' else [])
                   + [label for hz in ((TONE_HZ, LOW_TONE_HZ) if block == 'eq' else (TONE_HZ,))
                      for label in (f'{hz} Hz THD (dB)', f'{hz} Hz peak (dBFS)')])
        body += f'### Playback {block}\n\n' + markdown(columns, rows) + '\n'
    return body
